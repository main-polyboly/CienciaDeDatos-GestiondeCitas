class Cita {
    String paciente;
    String medico;
    String especialidad;
    String fecha;
    String hora;

    public Cita(String paciente, String medico, String especialidad, String fecha, String hora) {
        this.paciente = paciente;
        this.medico = medico;
        this.especialidad = especialidad;
        this.fecha = fecha;
        this.hora = hora;
    }
}